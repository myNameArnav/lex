#!/bin/sh
# Builds web/static/vendor/lexaudio/: the browser's AC-3/E-AC-3/DTS/TrueHD →
# AAC converter (wasm/audio/audio.c) linked against a minimal, LGPL-only
# FFmpeg. The result is committed, so this only runs when it changes.
#
# Uses emcc from PATH if there is one (source emsdk_env.sh first), otherwise
# the emscripten/emsdk image through docker or, without docker, rootful
# podman. Environment:
#   EMSDK_IMAGE  image to use (default: the 4.0.15 image for this machine)
#   JOBS         parallel make jobs (default: nproc); a killed build (out of
#                memory) is retried with one job
#   BUILD_DIR    where FFmpeg is built (default: a temporary directory); an
#                existing build with the same configuration is reused
set -eu

FFMPEG_VERSION=7.1.2
EMSDK_VERSION=4.0.15
# audio.c's codecs, in order. MLP comes with TrueHD.
DECODERS="ac3 eac3 dca truehd mlp"

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/web/static/vendor/lexaudio"

if ! command -v emcc >/dev/null 2>&1; then
  case $(uname -m) in
    aarch64 | arm64) image=${EMSDK_IMAGE:-docker.io/emscripten/emsdk:$EMSDK_VERSION-arm64} ;;
    *) image=${EMSDK_IMAGE:-docker.io/emscripten/emsdk:$EMSDK_VERSION} ;;
  esac
  if command -v docker >/dev/null 2>&1; then
    run="docker run"
  else
    run="sudo podman run"
  fi
  # Inside the container emcc is on PATH, so the script takes the branch below.
  exec $run --rm -u "$(id -u):$(id -g)" -e HOME=/tmp -e JOBS="${JOBS:-}" -e BUILD_DIR=/tmp/build \
    -v "$root:/src" -w /src "$image" sh scripts/build-audio-wasm.sh
fi

build=${BUILD_DIR:-$(mktemp -d)}
mkdir -p "$build" "$out"
cd "$build"
build=$(pwd)
flags="--cc=emcc --cxx=em++ --ar=emar --ranlib=emranlib --nm=emnm \
  --target-os=none --arch=x86_32 --enable-cross-compile --prefix=$build/ff \
  --disable-everything --disable-programs --disable-doc --disable-debug \
  --disable-avdevice --disable-avformat --disable-avfilter --disable-swscale \
  --disable-network --disable-pthreads --disable-w32threads --disable-os2threads \
  --disable-asm --disable-inline-asm --disable-x86asm --disable-runtime-cpudetect \
  --enable-decoder=$(echo $DECODERS | tr " " ,) --enable-encoder=aac \
  --extra-cflags=-O3"
if [ ! -f ff/lib/libavcodec.a ] || [ "$(cat ff/flags 2>/dev/null)" != "$FFMPEG_VERSION $flags" ]; then
  rm -rf "ffmpeg-$FFMPEG_VERSION" ff
  curl -fsSL "https://ffmpeg.org/releases/ffmpeg-$FFMPEG_VERSION.tar.xz" | tar xJ
  cd "ffmpeg-$FFMPEG_VERSION"
  # shellcheck disable=SC2086
  emconfigure ./configure $flags >/dev/null
  jobs=${JOBS:-$(nproc)}
  nice emmake make -j"$jobs" >/dev/null || nice emmake make -j1 >/dev/null
  emmake make install >/dev/null
  cp COPYING.LGPLv2.1 ../ff/
  echo "$FFMPEG_VERSION $flags" >../ff/flags
  cd ..
fi
emcc -O3 -I"$build/ff/include" "$root/wasm/audio/audio.c" \
  ff/lib/libavcodec.a ff/lib/libswresample.a ff/lib/libavutil.a \
  -s MODULARIZE=1 -s EXPORT_ES6=1 -s ENVIRONMENT=worker,node -s FILESYSTEM=0 \
  -s ALLOW_MEMORY_GROWTH=1 -s EXPORTED_RUNTIME_METHODS=HEAPU8 \
  -o "$out/audio.js"
cp ff/COPYING.LGPLv2.1 "$out/LICENSE"
# The player's caps probe offers to convert these, as the server names them.
list=
for d in $DECODERS; do
  [ "$d" = dca ] && d=dts
  list="$list${list:+, }'$d'"
done
printf '%s\n' "// Generated by scripts/build-audio-wasm.sh: the codecs audio.wasm decodes," \
  "// as the server names them." "export default [$list];" >"$out/codecs.js"
ls -l "$out"
